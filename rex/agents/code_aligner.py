"""Method-Code Alignment AST Visitor & Analyzer (REX-016 / Track A Sec 9-10).

Statically inspects Python code generated by the research platform to detect subtle
methodological-code divergences before execution:
1. Deterministic PRNG seeding (random, numpy, torch).
2. Data loader leakage (evaluating on train loader/split when reporting val/test metrics).
3. Unequal preprocessing pipelines between experimental arms.
4. Clean vs robust/adversarial accuracy mismatches.
"""

from __future__ import annotations

import ast
from enum import StrEnum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from rex.domain.models import ExperimentSpecification


class AlignmentIssueType(StrEnum):
    """Categorization of method-code misalignment defects."""

    MISSING_PRNG_SEEDING = "missing_prng_seeding"
    TRAIN_LEAKAGE_INTO_EVALUATION = "train_leakage_into_evaluation"
    UNEQUAL_PREPROCESSING = "unequal_preprocessing"
    CLEAN_VS_ROBUST_MISMATCH = "clean_vs_robust_mismatch"


class AlignmentIssue(BaseModel):
    """Diagnostic detail of a detected method-code misalignment."""

    model_config = ConfigDict(extra="forbid")

    issue_type: AlignmentIssueType = Field(description="Category of misalignment defect")
    severity: str = Field(default="critical", description="Severity level: critical or warning")
    description: str = Field(description="Clear explanation of the detected misalignment")
    line_number: int | None = Field(
        default=None, description="Source line number where defect was detected"
    )
    recommendation: str = Field(description="Specific remediation instructions")


class CodeAlignmentReport(BaseModel):
    """Overall evaluation report for method-code alignment."""

    model_config = ConfigDict(extra="forbid")

    is_aligned: bool = Field(description="True if code has zero critical method misalignments")
    issues: list[AlignmentIssue] = Field(
        default_factory=list, description="List of detected alignment issues"
    )
    prng_seeded: bool = Field(description="True if deterministic PRNG seeding was found")
    has_data_leakage: bool = Field(
        default=False, description="True if train-set leakage was detected in evaluation"
    )
    has_unequal_preprocessing: bool = Field(
        default=False, description="True if baseline and method use disparate preprocessing"
    )
    has_metric_mismatch: bool = Field(
        default=False, description="True if target metric contradicts evaluation logic"
    )
    alignment_score: float = Field(
        ge=0.0, le=1.0, description="Normalized alignment score (0.0 to 1.0)"
    )


class PRNGSeedVisitor(ast.NodeVisitor):
    """AST visitor checking whether deterministic PRNG seeds are explicitly set."""

    def __init__(self) -> None:
        self.uses_stochastic_modules = False
        self.imports_random = False
        self.imports_numpy = False
        self.imports_torch = False
        self.seeded_random = False
        self.seeded_numpy = False
        self.seeded_torch = False
        self.module_aliases: dict[str, str] = {}
        self.imported_seed_functions: dict[str, str] = {}
        self.local_functions: set[str] = set()

    def visit(self, node: ast.AST) -> Any:
        self.local_functions = {
            n.name for n in ast.walk(node) if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))
        }
        return super().visit(node)

    def visit_Import(self, node: ast.Import) -> None:
        for alias in node.names:
            base = alias.name.split(".")[0]
            local_name = alias.asname or alias.name
            self.module_aliases[local_name] = alias.name
            if base == "random":
                self.imports_random = True
            elif base == "numpy":
                self.imports_numpy = True
            elif base == "torch":
                self.imports_torch = True
            elif base in ("scipy", "sklearn"):
                self.uses_stochastic_modules = True
        self.generic_visit(node)

    def visit_ImportFrom(self, node: ast.ImportFrom) -> None:
        mod = node.module or ""
        base = mod.split(".")[0]
        if base == "random":
            self.imports_random = True
        elif base == "numpy":
            self.imports_numpy = True
        elif base == "torch":
            self.imports_torch = True
        elif base in ("scipy", "sklearn"):
            self.uses_stochastic_modules = True

        for alias in node.names:
            local_name = alias.asname or alias.name
            target = f"{mod}.{alias.name}" if mod else alias.name
            self.module_aliases[local_name] = target

            if mod == "random" and alias.name == "seed":
                self.imported_seed_functions[local_name] = "random"
            elif (mod == "numpy.random" or mod == "numpy") and alias.name in (
                "seed",
                "default_rng",
            ):
                self.imported_seed_functions[local_name] = "numpy"
            elif (mod == "torch" or mod.startswith("torch.")) and alias.name in (
                "manual_seed",
                "cuda",
                "manual_seed_all",
            ):
                self.imported_seed_functions[local_name] = "torch"
            elif alias.name == "seed_everything":
                self.imported_seed_functions[local_name] = "all"

        self.generic_visit(node)

    def visit_Call(self, node: ast.Call) -> None:
        if isinstance(node.func, ast.Name):
            func_name = node.func.id
            if func_name not in self.local_functions:
                if func_name == "seed_everything":
                    self.seeded_torch = True
                    self.seeded_numpy = True
                    self.seeded_random = True
                elif func_name in self.imported_seed_functions:
                    target = self.imported_seed_functions[func_name]
                    if target == "torch":
                        self.seeded_torch = True
                    elif target == "numpy":
                        self.seeded_numpy = True
                    elif target == "random":
                        self.seeded_random = True
                    elif target == "all":
                        self.seeded_torch = True
                        self.seeded_numpy = True
                        self.seeded_random = True

        call_str = self._resolve_call_name(node.func)

        if call_str in ("random.seed",):
            self.seeded_random = True

        if call_str in (
            "np.random.seed",
            "numpy.random.seed",
            "np.random.default_rng",
            "numpy.random.default_rng",
        ):
            self.seeded_numpy = True

        if call_str in (
            "torch.manual_seed",
            "torch.cuda.manual_seed",
            "torch.cuda.manual_seed_all",
            "seed_everything",
        ) or call_str.endswith(".seed_everything"):
            self.seeded_torch = True

        self.generic_visit(node)

    def _resolve_call_name(self, func: ast.AST) -> str:
        if isinstance(func, ast.Name):
            return self.module_aliases.get(func.id, func.id)
        if isinstance(func, ast.Attribute):
            val = self._resolve_call_name(func.value)
            return f"{val}.{func.attr}" if val else func.attr
        return ""


class DataLeakageVisitor(ast.NodeVisitor):
    """AST visitor checking whether train loader / train dataset leaks into evaluation."""

    def __init__(self) -> None:
        self.leakage_issues: list[tuple[int, str]] = []
        self._current_function: str = ""

    def visit_FunctionDef(self, node: ast.FunctionDef) -> None:
        old_fn = self._current_function
        self._current_function = node.name.lower()
        self.generic_visit(node)
        self._current_function = old_fn

    def visit_AsyncFunctionDef(self, node: ast.AsyncFunctionDef) -> None:
        old_fn = self._current_function
        self._current_function = node.name.lower()
        self.generic_visit(node)
        self._current_function = old_fn

    def visit_For(self, node: ast.For) -> None:
        iter_name = self._get_name(node.iter).lower()
        is_eval_context = any(
            ctx in self._current_function
            for ctx in ("eval", "validate", "val", "test", "benchmark", "inference")
        )

        train_identifiers = (
            "train_loader",
            "train_dataloader",
            "train_data",
            "train_dataset",
            "train_set",
        )
        if is_eval_context and any(tid in iter_name for tid in train_identifiers):
            self.leakage_issues.append(
                (
                    node.lineno,
                    f"Evaluation function '{self._current_function}' iterates over training source '{iter_name}' instead of validation/test split.",
                )
            )

        self.generic_visit(node)

    def visit_Call(self, node: ast.Call) -> None:
        call_name = self._resolve_call_name(node.func).lower()

        is_fit_call = (
            isinstance(node.func, ast.Attribute) and node.func.attr in ("fit", "fit_transform")
        ) or (isinstance(node.func, ast.Name) and node.func.id in ("fit", "fit_transform"))

        if is_fit_call:
            target_nodes = list(node.args) + [kw.value for kw in node.keywords]
            for arg in target_nodes:
                arg_name = self._get_name(arg).lower()
                if any(t in arg_name for t in ("test", "val", "evaluation")):
                    self.leakage_issues.append(
                        (
                            node.lineno,
                            f"Preprocessing '{call_name}' is fitted directly on evaluation data '{arg_name}', causing data leakage.",
                        )
                    )

        self.generic_visit(node)

    def _get_name(self, node: ast.AST) -> str:
        if isinstance(node, ast.Name):
            return node.id
        if isinstance(node, ast.Attribute):
            return f"{self._get_name(node.value)}.{node.attr}"
        if isinstance(node, ast.Call):
            return self._resolve_call_name(node.func)
        return ""

    def _resolve_call_name(self, func: ast.AST) -> str:
        if isinstance(func, ast.Name):
            return func.id
        if isinstance(func, ast.Attribute):
            val = self._resolve_call_name(func.value)
            return f"{val}.{func.attr}" if val else func.attr
        return ""


class PreprocessingVisitor(ast.NodeVisitor):
    """AST visitor inspecting preprocessing pipeline parity between arms."""

    def __init__(self) -> None:
        self.pipeline_transforms: dict[str, list[str]] = {}
        self._current_var: str = ""

    def visit_Assign(self, node: ast.Assign) -> None:
        for target in node.targets:
            if isinstance(target, ast.Name):
                var_name = target.id.lower()
                if "transform" in var_name or "pipeline" in var_name or "preprocess" in var_name:
                    ops = self._extract_call_ops(node.value)
                    self.pipeline_transforms[var_name] = ops
        self.generic_visit(node)

    def _extract_call_ops(self, node: ast.AST) -> list[str]:
        ops: list[str] = []
        if isinstance(node, ast.Call):
            name = self._get_call_name(node.func)
            if name:
                ops.append(name.lower())
            for arg in node.args:
                ops.extend(self._extract_call_ops(arg))
        elif isinstance(node, (ast.List, ast.Tuple)):
            for elt in node.elts:
                ops.extend(self._extract_call_ops(elt))
        return ops

    def _get_call_name(self, func: ast.AST) -> str:
        if isinstance(func, ast.Name):
            return func.id
        if isinstance(func, ast.Attribute):
            return func.attr
        return ""


class RobustAccuracyVisitor(ast.NodeVisitor):
    """AST visitor inspecting whether robust/adversarial metrics actually evaluate perturbed inputs."""

    def __init__(self) -> None:
        self.has_adversarial_generation = False
        self.adversarial_keywords = (
            "fgsm",
            "pgd",
            "attack",
            "perturb",
            "adversarial",
            "cleverhans",
            "foolbox",
            "torchattacks",
            "noise",
            "corrupt",
        )

    def visit_Call(self, node: ast.Call) -> None:
        call_name = self._get_full_call_name(node.func).lower()
        if any(kw in call_name for kw in self.adversarial_keywords):
            self.has_adversarial_generation = True
        self.generic_visit(node)

    def _get_full_call_name(self, func: ast.AST) -> str:
        if isinstance(func, ast.Name):
            return func.id
        if isinstance(func, ast.Attribute):
            val = self._get_full_call_name(func.value)
            return f"{val}.{func.attr}" if val else func.attr
        return ""

    def _get_name(self, node: ast.AST) -> str:
        if isinstance(node, ast.Name):
            return node.id
        if isinstance(node, ast.Attribute):
            return f"{self._get_name(node.value)}.{node.attr}"
        return ""


class MethodCodeAligner:
    """Deterministic method-code alignment verifier utilizing static AST parsing."""

    def align(
        self,
        source_code: str,
        specification: ExperimentSpecification | dict[str, Any] | None = None,
        expected_metrics: list[str] | None = None,
    ) -> CodeAlignmentReport:
        """Analyze source code against specification for semantic misalignments."""
        issues: list[AlignmentIssue] = []

        try:
            tree = ast.parse(source_code)
        except SyntaxError as e:
            return CodeAlignmentReport(
                is_aligned=False,
                issues=[
                    AlignmentIssue(
                        issue_type=AlignmentIssueType.MISSING_PRNG_SEEDING,
                        severity="critical",
                        description=f"SyntaxError in code: {e.msg}",
                        line_number=e.lineno,
                        recommendation="Fix Python syntax error.",
                    )
                ],
                prng_seeded=False,
                alignment_score=0.0,
            )

        # 1. PRNG Seeding Check
        seed_visitor = PRNGSeedVisitor()
        seed_visitor.visit(tree)

        seed_visitor.uses_stochastic_modules = (
            seed_visitor.uses_stochastic_modules
            or seed_visitor.imports_torch
            or seed_visitor.imports_numpy
            or seed_visitor.imports_random
        )

        missing_seeds: list[str] = []
        if seed_visitor.imports_torch and not seed_visitor.seeded_torch:
            missing_seeds.append("torch (e.g. torch.manual_seed)")
        if seed_visitor.imports_numpy and not seed_visitor.seeded_numpy:
            missing_seeds.append("numpy (e.g. np.random.seed)")
        if seed_visitor.imports_random and not seed_visitor.seeded_random:
            missing_seeds.append("random (e.g. random.seed)")
        if (
            seed_visitor.uses_stochastic_modules
            and not (
                seed_visitor.imports_torch
                or seed_visitor.imports_numpy
                or seed_visitor.imports_random
            )
            and not (
                seed_visitor.seeded_random or seed_visitor.seeded_numpy or seed_visitor.seeded_torch
            )
        ):
            missing_seeds.append("stochastic modules (missing PRNG initialization)")

        prng_seeded = len(missing_seeds) == 0

        if not prng_seeded:
            issues.append(
                AlignmentIssue(
                    issue_type=AlignmentIssueType.MISSING_PRNG_SEEDING,
                    severity="critical",
                    description=(
                        "Stochastic ML/data libraries are used without deterministic PRNG initialization: "
                        f"unseeded packages: {', '.join(missing_seeds)}."
                    ),
                    recommendation="Add explicit deterministic seeding (e.g. torch.manual_seed(seed); np.random.seed(seed); random.seed(seed)).",
                )
            )

        # 2. Train loader leakage check
        leakage_visitor = DataLeakageVisitor()
        leakage_visitor.visit(tree)
        has_data_leakage = len(leakage_visitor.leakage_issues) > 0

        for lineno, desc in leakage_visitor.leakage_issues:
            issues.append(
                AlignmentIssue(
                    issue_type=AlignmentIssueType.TRAIN_LEAKAGE_INTO_EVALUATION,
                    severity="critical",
                    description=desc,
                    line_number=lineno,
                    recommendation="Ensure evaluation routines iterate solely over validation or test splits.",
                )
            )

        # 3. Preprocessing Parity Check
        prep_visitor = PreprocessingVisitor()
        prep_visitor.visit(tree)
        has_unequal_preprocessing = False

        # If baseline and method transforms both exist, check if normalization or key transforms differ
        baseline_transforms = [
            t for k, t in prep_visitor.pipeline_transforms.items() if "base" in k or "control" in k
        ]
        treatment_keywords = ("method", "treatment", "model", "proposed", "experiment", "variant")
        method_transforms = [
            t
            for k, t in prep_visitor.pipeline_transforms.items()
            if any(kw in k for kw in treatment_keywords)
        ]

        if baseline_transforms and method_transforms:
            b_set = set(baseline_transforms[0])
            m_set = set(method_transforms[0])
            # Check for critical preprocessing operations like normalization or scaling
            normalization_ops = {"normalize", "standardscaler", "minmaxscaler", "scale"}
            b_norm = b_set & normalization_ops
            m_norm = m_set & normalization_ops
            if (b_norm and not m_norm) or (m_norm and not b_norm):
                has_unequal_preprocessing = True
                issues.append(
                    AlignmentIssue(
                        issue_type=AlignmentIssueType.UNEQUAL_PREPROCESSING,
                        severity="critical",
                        description=(
                            f"Unequal preprocessing detected between arms: baseline uses {b_set or 'raw features (no normalization)'} "
                            f"while proposed method uses {m_set or 'raw features (no normalization)'}. Normalization must be symmetric."
                        ),
                        recommendation="Apply identical preprocessing and normalization pipelines across all arms.",
                    )
                )

        # 4. Clean vs Robust Metric Mismatch
        has_metric_mismatch = False
        target_metrics: list[str] = []
        if expected_metrics:
            target_metrics.extend([m.lower() for m in expected_metrics])
        if specification:
            spec_dict = (
                specification.to_dict()
                if isinstance(specification, ExperimentSpecification)
                else specification
            )
            for m in spec_dict.get("metrics", []):
                if isinstance(m, dict):
                    target_metrics.append(str(m.get("name", "")).lower())
                elif isinstance(m, str):
                    target_metrics.append(m.lower())

        is_robust_metric = any(
            "robust" in m or "adversarial" in m or "perturbed" in m for m in target_metrics
        )
        if is_robust_metric:
            robust_visitor = RobustAccuracyVisitor()
            robust_visitor.visit(tree)
            if not robust_visitor.has_adversarial_generation:
                has_metric_mismatch = True
                issues.append(
                    AlignmentIssue(
                        issue_type=AlignmentIssueType.CLEAN_VS_ROBUST_MISMATCH,
                        severity="critical",
                        description=(
                            "Metric specification requires robust/adversarial accuracy, but code evaluates "
                            "clean unmodified inputs without applying adversarial perturbations or attacks."
                        ),
                        recommendation="Generate adversarial perturbations (e.g. FGSM/PGD) during evaluation.",
                    )
                )

        critical_count = sum(1 for i in issues if i.severity == "critical")
        score = max(0.0, 1.0 - (critical_count * 0.35) - (len(issues) * 0.1))
        is_aligned = critical_count == 0

        return CodeAlignmentReport(
            is_aligned=is_aligned,
            issues=issues,
            prng_seeded=prng_seeded,
            has_data_leakage=has_data_leakage,
            has_unequal_preprocessing=has_unequal_preprocessing,
            has_metric_mismatch=has_metric_mismatch,
            alignment_score=round(score, 3),
        )

    def verify_files(
        self,
        source_files: dict[str, str],
        specification: ExperimentSpecification | dict[str, Any] | None = None,
    ) -> CodeAlignmentReport:
        """Verify method-code alignment across an entire multi-file codebase package."""
        all_issues: list[AlignmentIssue] = []
        prng_seeded = False
        has_leakage = False
        has_unequal = False
        has_mismatch = False

        for content in source_files.values():
            rep = self.align(content, specification=specification)
            all_issues.extend(rep.issues)
            if rep.prng_seeded:
                prng_seeded = True
            if rep.has_data_leakage:
                has_leakage = True
            if rep.has_unequal_preprocessing:
                has_unequal = True
            if rep.has_metric_mismatch:
                has_mismatch = True

        critical_count = sum(1 for i in all_issues if i.severity == "critical")
        score = max(0.0, 1.0 - (critical_count * 0.35) - (len(all_issues) * 0.1))
        is_aligned = critical_count == 0

        return CodeAlignmentReport(
            is_aligned=is_aligned,
            issues=all_issues,
            prng_seeded=prng_seeded,
            has_data_leakage=has_leakage,
            has_unequal_preprocessing=has_unequal,
            has_metric_mismatch=has_mismatch,
            alignment_score=round(score, 3),
        )
