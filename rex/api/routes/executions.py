"""Execution & Run telemetry API endpoints (REX-037, REX-039).

Provides inspection of execution records, environment fingerprints, hardware telemetry,
raw captured logs, and empirical result metrics.
"""

from __future__ import annotations

from pathlib import Path

from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy import select
from sqlalchemy.orm import Session

from rex.api.routes.research import get_db
from rex.api.schemas import (
    ArtifactResponse,
    ExecutionResponse,
    ResultResponse,
)
from rex.config import get_settings
from rex.execution.canaries import scrub_logs_and_credentials
from rex.persistence.models import (
    ArtifactModel,
    ExecutionModel,
    ResultModel,
)

router = APIRouter(prefix="/runs", tags=["executions"])


@router.get("/{execution_id}", response_model=ExecutionResponse)
def get_execution(
    execution_id: str,
    session: Session = Depends(get_db),
) -> ExecutionResponse:
    """Retrieve full execution telemetry and provenance hashes."""
    model = session.get(ExecutionModel, execution_id)
    if not model:
        raise HTTPException(status_code=404, detail=f"Execution '{execution_id}' not found.")

    duration = None
    if model.started_at and model.finished_at:
        duration = (model.finished_at - model.started_at).total_seconds()
    elif isinstance(model.resource_usage_json, dict):
        duration = model.resource_usage_json.get("duration_seconds")

    return ExecutionResponse(
        id=model.id,
        experiment_id=model.experiment_id,
        status=model.status,
        started_at=model.started_at,
        finished_at=model.finished_at,
        command=model.command,
        git_commit=model.git_commit,
        code_hash=model.code_hash,
        dataset_hash=model.dataset_hash,
        configuration_hash=model.configuration_hash,
        seed=model.seed,
        environment=model.environment_json or {},
        resource_usage=model.resource_usage_json or {},
        exit_code=model.exit_code,
        stdout_artifact_id=model.stdout_artifact_id,
        stderr_artifact_id=model.stderr_artifact_id,
        duration_seconds=duration,
    )


@router.get("/{execution_id}/results", response_model=list[ResultResponse])
def list_execution_results(
    execution_id: str,
    session: Session = Depends(get_db),
) -> list[ResultResponse]:
    """List empirical result metrics recorded for an execution."""
    stmt = (
        select(ResultModel)
        .where(ResultModel.execution_id == execution_id)
        .order_by(ResultModel.created_at.asc())
    )
    models = session.scalars(stmt).all()
    return [
        ResultResponse(
            id=m.id,
            execution_id=m.execution_id,
            metric_name=m.metric_name,
            metric_value=m.metric_value,
            metric_unit=m.metric_unit,
            result_data=m.result_json or {},
            created_at=m.created_at,
        )
        for m in models
    ]


@router.get("/{execution_id}/artifacts", response_model=list[ArtifactResponse])
def list_execution_artifacts(
    execution_id: str,
    session: Session = Depends(get_db),
) -> list[ArtifactResponse]:
    """List disk artifacts generated by this execution."""
    stmt = (
        select(ArtifactModel)
        .where(ArtifactModel.execution_id == execution_id)
        .order_by(ArtifactModel.created_at.asc())
    )
    models = session.scalars(stmt).all()
    return [
        ArtifactResponse(
            id=m.id,
            research_run_id=m.research_run_id,
            execution_id=m.execution_id,
            artifact_type=m.artifact_type,
            path=m.path,
            content_hash=m.content_hash,
            size_bytes=m.size_bytes,
            metadata=m.metadata_json or {},
            created_at=m.created_at,
        )
        for m in models
    ]


@router.get("/{execution_id}/logs")
def get_execution_logs(
    execution_id: str,
    session: Session = Depends(get_db),
) -> dict[str, str]:
    """Retrieve raw stdout and stderr output strings from disk or stored artifacts."""
    model = session.get(ExecutionModel, execution_id)
    if not model:
        raise HTTPException(status_code=404, detail=f"Execution '{execution_id}' not found.")

    artifact_root = get_settings().persistence.artifact_root
    stdout_content = ""
    stderr_content = ""

    if model.stdout_artifact_id:
        art = session.get(ArtifactModel, model.stdout_artifact_id)
        if art:
            p = Path(art.path)
            if not p.is_absolute():
                p = artifact_root / p
            if p.exists():
                try:
                    stdout_content = p.read_text(encoding="utf-8", errors="replace")
                except OSError:
                    stdout_content = "[Error reading stdout file]"

    if model.stderr_artifact_id:
        art = session.get(ArtifactModel, model.stderr_artifact_id)
        if art:
            p = Path(art.path)
            if not p.is_absolute():
                p = artifact_root / p
            if p.exists():
                try:
                    stderr_content = p.read_text(encoding="utf-8", errors="replace")
                except OSError:
                    stderr_content = "[Error reading stderr file]"

    return {
        "execution_id": execution_id,
        "stdout": scrub_logs_and_credentials(stdout_content),
        "stderr": scrub_logs_and_credentials(stderr_content),
        "exit_code": str(model.exit_code) if model.exit_code is not None else "",
    }
